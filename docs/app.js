function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function renderChatText(value) {
  const paragraph = el('p', 'chat-text');
  const skillName = /\b(coordination|implementation|analysis|verification)\b/g;
  let cursor = 0;
  for (const match of value.matchAll(skillName)) {
    const before = value.slice(0, match.index);
    const after = value.slice(match.index + match[0].length);
    const isSkill = /(?:the |навык )$/.test(before) && (/^ skill\b/.test(after) || /навык $/.test(before));
    if (!isSkill) continue;
    paragraph.append(document.createTextNode(value.slice(cursor, match.index)));
    paragraph.append(el('span', 'skill-name', match[0]));
    cursor = match.index + match[0].length;
  }
  paragraph.append(document.createTextNode(value.slice(cursor)));
  return paragraph;
}

function renderNote(note, lang) {
  const aside = el('aside', 'system-note');
  const portrait = el('div', 'note-figure');
  portrait.append(el('span', 'note-label', COPY[lang].systemNote));
  const image = el('img');
  image.src = './assets/developer/scene-' + String(note.image || 13).padStart(2, '0') + '.png';
  image.loading = 'lazy';
  image.decoding = 'async';
  image.alt = COPY[lang].developerAlt;
  portrait.append(image);
  aside.append(portrait);
  const content = el('div', 'note-body');
  content.innerHTML = note[lang];
  content.querySelectorAll('a').forEach(link => {
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
  });
  aside.append(content);
  return aside;
}

function renderParticipant(person, scene, lang, position) {
  const figure = el('figure', 'participant participant-' + position + (person === 'user' ? ' participant-human' : ' participant-agent'));
  const image = el('img');
  image.src = person === 'user'
    ? './assets/developer/scene-' + String(scene.image || scene.id).padStart(2, '0') + '.png'
    : './assets/agents/' + person + '.png';
  image.loading = scene.id < 3 ? 'eager' : 'lazy';
  image.decoding = 'async';
  image.alt = person === 'user'
    ? (scene.pair.length === 0 ? COPY[lang].readingAlt : COPY[lang].developerAlt)
    : COPY[lang].agentAlt.replace('{name}', COPY[lang].names[person]);
  figure.append(image);
  figure.append(el('figcaption', 'participant-name', COPY[lang].names[person]));
  return figure;
}

function renderChat(scene, lang) {
  const chat = el('div', 'chat-thread');
  chat.setAttribute('role', 'group');
  chat.setAttribute('aria-label', COPY[lang].names[scene.pair[0]] + ' — ' + COPY[lang].names[scene.pair[1]]);
  const header = el('div', 'chat-thread-header');
  header.append(el('span', 'chat-status'));
  header.append(el('span', 'chat-heading', COPY[lang].exampleExchange));
  chat.append(header);
  const messages = el('div', 'chat-messages');
  messages.setAttribute('role', 'list');
  scene.lines.forEach(line => {
    const starts = line[0] === scene.pair[0];
    const entry = el('div', 'chat-entry ' + (starts ? 'chat-entry-initiator' : 'chat-entry-responder'));
    entry.setAttribute('role', 'listitem');
    entry.append(el('span', 'chat-speaker', COPY[lang].names[line[0]]));
    entry.append(renderChatText(line[lang === 'ru' ? 2 : 1]));
    messages.append(entry);
  });
  chat.append(messages);
  if (scene.statuses?.lines?.length) {
    const progress = el('div', 'chat-progress chat-progress-' + scene.statuses.kind);
    progress.setAttribute('role', 'list');
    progress.setAttribute('aria-label', COPY[lang].activityLabel);
    scene.statuses.lines.forEach((line, index) => {
      const step = el('div', 'chat-progress-step' + (scene.statuses.kind === 'send' && index === scene.statuses.lines.length - 1 ? ' chat-progress-step-done' : ''));
      step.setAttribute('role', 'listitem');
      const icon = el('span', 'chat-progress-icon');
      icon.setAttribute('aria-hidden', 'true');
      step.append(icon, el('span', null, line[lang === 'ru' ? 1 : 0]));
      progress.append(step);
    });
    chat.append(progress);
  }
  return chat;
}

function renderScene(scene, lang) {
  const frame = el('section', 'comic-scene');
  const reading = scene.pair.length === 0;
  if (reading) frame.classList.add('reading-scene');
  else {
    frame.classList.add('dialogue-scene');
    frame.classList.add(scene.pair.includes('user') ? 'user-agent-scene' : 'agent-pair-scene');
  }
  frame.id = 'scene-' + scene.id;
  frame.setAttribute('aria-labelledby', 'scene-title-' + scene.id);
  const heading = el('div', 'scene-heading');
  heading.append(el('span', 'scene-count', String(scene.id).padStart(2, '0') + ' / ' + SCENES.length));
  const h2 = el('h2', null, scene.title[lang === 'ru' ? 1 : 0]);
  h2.id = 'scene-title-' + scene.id;
  heading.append(h2);
  frame.append(heading);

  const stage = el('div', 'scene-stage');
  if (reading) {
    stage.append(renderParticipant('user', scene, lang, 'initiator'));
    const pause = el('div', 'reading-stage');
    pause.append(el('p', null, COPY[lang].reader));
    stage.append(pause);
  } else {
    stage.append(renderParticipant(scene.pair[0], scene, lang, 'initiator'));
    stage.append(renderChat(scene, lang));
    stage.append(renderParticipant(scene.pair[1], scene, lang, 'responder'));
  }
  frame.append(stage);
  return frame;
}

function markDialogueRuns() {
  let run = [];
  function markRun() {
    if (run.length > 1) run.forEach((frame, index) => {
      frame.classList.add('dialogue-run', index % 2 === 0 ? 'dialogue-shift-left' : 'dialogue-shift-right');
    });
    run = [];
  }
  for (const child of comic.children) {
    if (child.classList.contains('dialogue-scene')) run.push(child);
    else markRun();
  }
  markRun();
}

function renderGuide(lang) {
  guideGrid.replaceChildren();
  GUIDE.forEach((item, index) => {
    const content = item[lang];
    const article = el('article', 'guide-item');
    article.append(el('span', 'guide-index', String(index + 1).padStart(2, '0')));
    article.append(el('h3', null, content[0]));
    article.append(el('p', null, content[1]));
    const link = el('a', null, content[2]);
    link.href = item.url;
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    article.append(link);
    guideGrid.append(article);
  });
}

function renderGalleryAlts(lang) {
  document.querySelectorAll('.gallery-grid img').forEach(image => {
    const source = image.getAttribute('src') || '';
    if (source.endsWith('/hero.png')) image.alt = COPY[lang].galleryHeroAlt;
    else if (source.endsWith('/scene-13.png')) image.alt = COPY[lang].galleryReadingAlt;
    else if (source.includes('/developer/')) {
      const number = source.match(/scene-(\d+)\.png$/)?.[1];
      image.alt = COPY[lang].gallerySceneAlt.replace('{number}', number || '');
    } else if (source.includes('/agents/')) {
      const name = source.match(/\/([a-z]+)\.png$/)?.[1] || '';
      image.alt = COPY[lang].galleryAgentAlt.replace('{name}', COPY[lang].names[name] || name);
    } else image.alt = COPY[lang].galleryIconAlt;
  });
}

function render(lang) {
  document.documentElement.lang = lang;
  document.title = COPY[lang][document.body.classList.contains('gallery-page') ? 'galleryPageTitle' : 'pageTitle'];
  document.querySelectorAll('[data-copy]').forEach(node => { node.textContent = COPY[lang][node.dataset.copy]; });
  document.querySelectorAll('[data-html]').forEach(node => { node.innerHTML = COPY[lang][node.dataset.html]; });
  document.querySelectorAll('[data-aria]').forEach(node => { node.setAttribute('aria-label', COPY[lang][node.dataset.aria]); });
  document.querySelectorAll('[data-lang]').forEach(button => { button.setAttribute('aria-pressed', String(button.dataset.lang === lang)); });
  if (comic) {
    comic.replaceChildren();
    NOTES.filter(note => note.after === 0).forEach(note => comic.append(renderNote(note, lang)));
    SCENES.forEach(scene => {
      comic.append(renderScene(scene, lang));
      NOTES.filter(note => note.after === scene.id).forEach(note => comic.append(renderNote(note, lang)));
    });
    markDialogueRuns();
  }
  if (guideGrid) renderGuide(lang);
  if (document.body.classList.contains('gallery-page')) renderGalleryAlts(lang);
}

document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click', () => {
  const lang = button.dataset.lang;
  try { localStorage.setItem('ncf-site-language', lang); } catch (_) { /* Storage may be unavailable. */ }
  render(lang);
}));
