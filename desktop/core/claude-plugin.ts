import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { claudePlugin } from '../integrations/claude-code.js';
import { claudeToolPrefix } from './claude-sessions.js';
import { wakeNoticePrefix } from './claude-wake.js';

export interface ClaudePluginRuntime {
  /** The installed executable: Electron in packages, Node.js in source checks. */
  execPath: string;
  /** Interpreter arguments before the script, empty in packages. */
  runtimeArgs: string[];
  script: string;
  nodeFile: string;
  platform: NodeJS.Platform;
  version: string;
}

const powershellLiteral = (value: string) => "'" + value.replaceAll("'", "''") + "'";

/**
 * Hooks have no env field. POSIX uses exec form through /usr/bin/env, so no
 * shell parses a path. Windows uses PowerShell with single-quoted literals,
 * where only a doubled quote is special.
 */
function commandHook(runtime: ClaudePluginRuntime) {
  const argv = [...runtime.runtimeArgs, runtime.script, '--hook', '--node-file', runtime.nodeFile];
  if (runtime.platform === 'win32')
    return {
      type: 'command',
      shell: 'powershell',
      command:
        "$env:ELECTRON_RUN_AS_NODE='1'; & " +
        [runtime.execPath, ...argv].map(powershellLiteral).join(' '),
      timeout: 15,
    };
  return {
    type: 'command',
    command: '/usr/bin/env',
    args: ['ELECTRON_RUN_AS_NODE=1', runtime.execPath, ...argv],
    timeout: 10,
  };
}

/**
 * The main plugin's mod. At session start it spawns the installed runtime as the
 * wake stream of this exact native session; for each claimed wake it consumes
 * the claim and submits the node's notice with plugin attribution, never
 * asUser and never retried. Its lifecycle scope is allocated before any await
 * and rechecked after each one; session.end ends the stream. It never reads an
 * inbox. The gate plugin, which this plugin depends on, checks each notice
 * right before it starts a turn.
 */
function wakeModule(runtime: ClaudePluginRuntime): string {
  const argv = [
    runtime.execPath,
    ...runtime.runtimeArgs,
    runtime.script,
    '--wake-stream',
    '--node-file',
    runtime.nodeFile,
  ];
  return `// Generated by NCF Agent Interconnect for this installation. Do not edit.
const nodeFile = ${JSON.stringify(runtime.nodeFile)};
const streamArgv = ${JSON.stringify(argv)};
const prefix = ${JSON.stringify(wakeNoticePrefix)};

let scope = null;
const current = (own) => own.current && scope === own;
function end(own) {
  own.current = false;
  const stream = own.stream;
  own.stream = null;
  if (stream) Promise.resolve(stream.return()).catch(() => {});
}

export function register(on) {
  on('session.start', ($, e, next) => {
    if (scope) end(scope);
    const own = { current: true, stream: null };
    scope = own;
    // Not awaited: the stream lives as long as this session's lifecycle.
    run($, own).catch(() => {});
    return next(e);
  });
  on('session.end', ($, e, next) => {
    // /clear, /resume, /branch and exit end the stream; nothing is resubmitted.
    if (scope) end(scope);
    scope = null;
    return next(e);
  });
}

async function run($, own) {
  const sessionId = await $.session.id();
  if (!current(own)) return;
  const descriptor = JSON.parse(await $.fs.read(nodeFile));
  if (!current(own) || typeof descriptor.url !== 'string' || typeof descriptor.token !== 'string')
    return;
  const stream = $.process.spawn({
    argv: [...streamArgv, '--session', sessionId],
    env: { ELECTRON_RUN_AS_NODE: '1' },
  });
  own.stream = stream;
  let buffer = '';
  for await (const chunk of stream) {
    if (!current(own)) break;
    if (chunk.stream !== 'stdout') continue;
    buffer += chunk.text;
    if (buffer.length > 65536) break;
    let index;
    while ((index = buffer.indexOf('\\n')) >= 0) {
      const line = buffer.slice(0, index);
      buffer = buffer.slice(index + 1);
      let wake;
      try {
        wake = JSON.parse(line);
      } catch {
        continue;
      }
      if (wake && wake.type === 'wake') submit($, own, descriptor, sessionId, wake).catch(() => {});
    }
  }
}

async function submit($, own, descriptor, sessionId, wake) {
  if (
    !current(own) ||
    typeof wake.claim !== 'string' ||
    typeof wake.notice !== 'string' ||
    wake.notice.length > 1000 ||
    !wake.notice.startsWith(prefix) ||
    /[\\u0000-\\u001f\\u007f]/.test(wake.notice)
  )
    return;
  const response = await $.http.fetch(new URL('/integrations/claude/wake/claim', descriptor.url).href, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: 'Bearer ' + descriptor.token },
    body: JSON.stringify({ sessionId, claim: wake.claim }),
  });
  if (!response.ok || !current(own)) return;
  const answer = JSON.parse(response.text);
  // Consumed immediately before submit; no await separates the check from it.
  if (answer.consumed !== true || !current(own)) return;
  const result = await $.prompt.submit({ text: wake.notice });
  // Never resubmitted; the node only learns that this notice no longer covers the backlog.
  if (result && typeof result.drop === 'string')
    await $.http.fetch(new URL('/integrations/claude/wake/dropped', descriptor.url).href, {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: 'Bearer ' + descriptor.token },
      body: JSON.stringify({ sessionId, claim: wake.claim }),
    });
}
`;
}

/**
 * The gate plugin's mod. A mod's own hooks never see its own submission; this
 * gate runs after the main plugin and sees its notice when it is dequeued,
 * right before the turn. It names the exact notice to the node by the SHA-256
 * of its text and lets it through only if the node starts that notice's claim
 * and this lifecycle is still current after the last await. Owner prompts pass
 * unchanged; a failed or timed-out check drops the notice.
 */
function gateModule(runtime: ClaudePluginRuntime): string {
  return `// Generated by NCF Agent Interconnect for this installation. Do not edit.
const nodeFile = ${JSON.stringify(runtime.nodeFile)};
const source = ${JSON.stringify(claudePlugin.name)};
const prefix = ${JSON.stringify(wakeNoticePrefix)};

let lifecycle = null;
const current = (own) => !!own && !own.ended && lifecycle === own;

export function gated(origin, text) {
  return !!origin && origin.plugin === source && typeof text === 'string' && text.startsWith(prefix);
}

export function register(on) {
  on('session.start', ($, e, next) => {
    if (lifecycle) lifecycle.ended = true;
    const own = { ended: false, descriptor: null };
    own.loading = $.fs
      .read(nodeFile)
      .then((text) => {
        const value = JSON.parse(text);
        if (typeof value.url === 'string' && typeof value.token === 'string') own.descriptor = value;
      })
      .catch(() => {});
    lifecycle = own;
    return next(e);
  });
  on('session.end', ($, e, next) => {
    if (lifecycle) lifecycle.ended = true;
    lifecycle = null;
    return next(e);
  });
  on('prompt.submit', async ($, e, next) => {
    if (!gated(next.origin, e.text)) return next(e);
    const refusal = await check($, lifecycle, e.text);
    return refusal ? { drop: refusal } : next(e);
  }).catch(($, e, next) => {
    if (next.called || !gated(next.origin, e.text)) return next(e);
    return { drop: 'NCF wake notice withdrawn: the check failed. Messages stay unread.' };
  });
}

async function sha256(text) {
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

const ended = 'NCF wake notice from an ended session lifecycle. Messages stay unread.';

async function check($, own, text) {
  if (!current(own)) return ended;
  await own.loading;
  if (!current(own)) return ended;
  if (!own.descriptor) return 'NCF wake notice withdrawn: NCF Agent Interconnect is not running.';
  const sessionId = await $.session.id();
  if (!current(own)) return ended;
  const notice = await sha256(text);
  if (!current(own)) return ended;
  const response = await $.http.fetch(new URL('/integrations/claude/wake/start', own.descriptor.url).href, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: 'Bearer ' + own.descriptor.token },
    body: JSON.stringify({ sessionId, notice }),
  });
  const answer = response.ok ? JSON.parse(response.text) : {};
  // The final authorization: no await follows before the notice is forwarded.
  if (!current(own)) return ended;
  if (answer.started === true) return null;
  if (answer.reason === 'backlog-read')
    return 'NCF wake notice withdrawn: the waiting messages were already read.';
  return 'NCF wake notice withdrawn (' + String(answer.reason || 'refused') + '). Messages stay unread.';
}
`;
}

/** Files of the local marketplace published from the installed application. */
export function claudePluginFiles(runtime: ClaudePluginRuntime): Record<string, string> {
  const paths = runtime.platform === 'win32' ? path.win32 : path.posix;
  for (const value of [runtime.execPath, runtime.script, runtime.nodeFile])
    if (!paths.isAbsolute(value) || /[\0\r\n]/.test(value) || value.includes('${'))
      throw new Error('The installed NCF path cannot be used by the Claude Code plugin');
  const hook = commandHook(runtime);
  const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';
  return {
    '.claude-plugin/marketplace.json': json({
      name: claudePlugin.marketplace,
      owner: { name: 'NCF Agent Interconnect' },
      description: 'Published by the installed NCF Agent Interconnect application.',
      plugins: [
        {
          name: claudePlugin.name,
          source: './plugin',
          description: 'Connects this Claude Code chat to NCF Agent Interconnect.',
        },
        {
          name: claudePlugin.gate,
          source: './gate',
          description: 'Checks NCF wake notices right before they start a turn.',
        },
      ],
    }),
    'plugin/.claude-plugin/plugin.json': json({
      name: claudePlugin.name,
      displayName: 'NCF Agent Interconnect',
      version: runtime.version,
      description:
        'Messages for agents connected through NCF Agent Interconnect, announced by a channel and received with agent_read.',
      author: { name: 'no-colours-fabric' },
      license: 'BSD-3-Clause',
      mcpServers: {
        [claudePlugin.server]: {
          command: runtime.execPath,
          args: [...runtime.runtimeArgs, runtime.script, '--node-file', runtime.nodeFile],
          env: { ELECTRON_RUN_AS_NODE: '1' },
        },
      },
      channels: [{ server: claudePlugin.server, displayName: 'NCF Agent Interconnect' }],
      // The documented mod order: this plugin's mod runs before the gate's, so the
      // gate sees each notice. A missing, disabled or mismatched gate stops this
      // plugin from loading instead of letting notices through unchecked.
      dependencies: [{ name: claudePlugin.gate, version: '=' + runtime.version }],
    }),
    'plugin/hooks/hooks.json': json({
      description: 'Trusted current-chat evidence and wake notices for NCF Agent Interconnect.',
      modules: ['./wake.js'],
      hooks: {
        // Native lifecycle evidence is private command-hook state. A model-visible
        // MCP tool cannot authenticate a context switch.
        SessionStart: [{ hooks: [hook] }],
        SessionEnd: [{ hooks: [hook] }],
        PreToolUse: [{ matcher: claudeToolPrefix.replace(/__$/, '__.*'), hooks: [hook] }],
        // Observation only: the hook prints nothing and never blocks the stop.
        Stop: [{ hooks: [hook] }],
      },
    }),
    'plugin/hooks/wake.js': wakeModule(runtime),
    'gate/.claude-plugin/plugin.json': json({
      name: claudePlugin.gate,
      displayName: 'NCF Agent Interconnect gate',
      version: runtime.version,
      description:
        'Lets an NCF Agent Interconnect wake notice start a turn only while its one-use claim is current.',
      author: { name: 'no-colours-fabric' },
      license: 'BSD-3-Clause',
    }),
    'gate/hooks/hooks.json': json({
      description: 'NCF wake notice gate.',
      modules: ['./gate.js'],
    }),
    'gate/hooks/gate.js': gateModule(runtime),
  };
}

/** Writes changed files only, each through a private temporary file. */
export async function publishClaudePlugin(
  root: string,
  files: Record<string, string>,
): Promise<void> {
  for (const [relative, content] of Object.entries(files)) {
    const target = path.join(root, ...relative.split('/'));
    const current = await readFile(target, 'utf8').catch(() => undefined);
    if (current === content) continue;
    await mkdir(path.dirname(target), { recursive: true, mode: 0o700 });
    const temporary = target + '.' + randomUUID() + '.tmp';
    await writeFile(temporary, content, { mode: 0o600, flag: 'wx' });
    await rename(temporary, target);
  }
}
