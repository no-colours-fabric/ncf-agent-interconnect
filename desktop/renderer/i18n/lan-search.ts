export function lanSearchMessages(locale: Locale): LanSearchMessages {
  return { ...dictionaries[locale] };
}

export function formatLanSearch(message: string, values: Record<string, string | number>): string {
  return message.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}
